MEMBER = 'coronacases_001.nii.gz'
SHAPE = (4, 5, 9)


def nifti_bytes(*, version=1, mask=False, affine=None, slope=None,
                conflicting_forms=False, fractional_mask=False):
    """Return a real serialized generated NIfTI, without reading any file."""
    affine = np.diag([0.7, 0.8, 1.3, 1.0]) if affine is None else affine
    if mask:
        data = np.zeros(SHAPE, dtype=np.float32 if fractional_mask else np.uint8)
        data[1:3, 1:4, 2:7] = 0.5 if fractional_mask else 1
    else:
        data = np.arange(np.prod(SHAPE), dtype=np.int16).reshape(SHAPE)
    cls = nib.Nifti1Image if version == 1 else nib.Nifti2Image
    image = cls(data, affine)
    image.header.set_xyzt_units('mm')
    image.set_qform(affine, code=1)
    sform = np.array(affine, copy=True)
    if conflicting_forms:
        sform[0, 3] += 7.0
    image.set_sform(sform, code=1)
    if slope is not None:
        image.header.set_slope_inter(*slope)
    return image.to_bytes()


def gzip_bytes(payload, fault=None):
    body = gzip.compress(payload, mtime=0)
    if fault == 'crc':
        body = body[:-8] + bytes([body[-8] ^ 1]) + body[-7:]
    elif fault == 'isize':
        body = body[:-4] + struct.pack('<I', (len(payload) + 1) & 0xffffffff)
    elif fault == 'truncated':
        body = body[:-5]
    elif fault == 'extra_stream':
        body += gzip.compress(b'GENERATED_SECOND_STREAM', mtime=0)
    elif fault == 'trailing':
        body += b'GENERATED_TRAILING_GARBAGE'
    return body


def archive_bytes(payload, fault=None):
    """Create a genuine ZIP; faults affect only generated bytes and metadata."""
    class Unseekable(io.BytesIO):
        def seekable(self):
            return False

        def seek(self, *args, **kwargs):
            raise io.UnsupportedOperation('generated non-seekable writer')

    descriptor = fault is not None and fault.startswith('descriptor_')
    stream = Unseekable() if descriptor else io.BytesIO()
    with zipfile.ZipFile(stream, 'w', compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(MEMBER, payload)
    data = bytearray(stream.getvalue())
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        member = archive.getinfo(MEMBER)
    offset = member.header_offset
    name_length, extra_length = struct.unpack_from('<HH', data, offset + 26)
    start = offset + 30 + name_length + extra_length
    end = start + member.compress_size
    central = end + (16 if descriptor else 0)
    assert data[central:central + 4] == b'PK\x01\x02'
    if descriptor:
        assert member.flag_bits & 8
        assert data[end:end + 4] == b'PK\x07\x08'
        if fault == 'descriptor_crc':
            struct.pack_into('<I', data, end + 4, member.CRC ^ 1)
        elif fault == 'descriptor_size':
            struct.pack_into('<I', data, end + 8, member.compress_size + 1)
        elif fault in ('descriptor_missing', 'descriptor_unsigned'):
            removed = 16 if fault == 'descriptor_missing' else 4
            del data[end:end + removed]
            central -= removed
            eocd = data.rfind(b'PK\x05\x06')
            struct.pack_into('<I', data, eocd + 16, central)
    elif fault in ('deflate_truncated', 'deflate_trailing'):
        replacement = bytes(data[start:end])
        replacement = replacement[:-1] if fault == 'deflate_truncated' else replacement + b'EXTRA'
        delta = len(replacement) - (end - start)
        data[start:end] = replacement
        central += delta
        struct.pack_into('<I', data, offset + 18, len(replacement))
        struct.pack_into('<I', data, central + 20, len(replacement))
        eocd = data.rfind(b'PK\x05\x06')
        struct.pack_into('<I', data, eocd + 16, central)
    elif fault == 'crc':
        wrong = member.CRC ^ 1
        struct.pack_into('<I', data, offset + 14, wrong)
        struct.pack_into('<I', data, central + 16, wrong)
    return bytes(data)


def target(tmp_path, role, payload, *, zip_fault=None):
    path = tmp_path / (role + '.zip')
    path.write_bytes(archive_bytes(payload, zip_fault))
    with zipfile.ZipFile(path) as archive:
        member = archive.getinfo(MEMBER)
    stat = path.stat()
    return {
        'role': role,
        'archive': {
            'path': str(path), 'bytes': stat.st_size, 'device': stat.st_dev,
            'inode': stat.st_ino, 'mtime_ns': stat.st_mtime_ns,
            'stream_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
        },
        'member': {
            'name': MEMBER, 'header_offset': member.header_offset,
            'compression': member.compress_type,
            'compressed_bytes': member.compress_size,
            'uncompressed_bytes': member.file_size,
            'declared_crc32': member.CRC,
        },
    }


def inputs(tmp_path, *, version=1, inner_fault=None, zip_fault=None,
           ct_options=None, mask_options=None):
    tmp_path.mkdir(parents=True, exist_ok=True)
    ct = gzip_bytes(nifti_bytes(version=version, **(ct_options or {})), inner_fault)
    mask = gzip_bytes(nifti_bytes(version=version, mask=True, **(mask_options or {})))
    return {
        'output_root': str(tmp_path / 'qualification-output'),
        'targets': [target(tmp_path, 'CT', ct, zip_fault=zip_fault),
                    target(tmp_path, 'INFECTION_MASK', mask)],
        'limits': dict(qualification.LIMITS),
        'evidence': {}, 'preprocess': {},
    }


def result_text(result):
    return json.dumps(result, sort_keys=True).lower()


