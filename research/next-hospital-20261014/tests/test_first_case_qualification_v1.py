def test_validate_uses_metadata_only_and_never_opens_archives(tmp_path, monkeypatch):
    q = inputs(tmp_path)
    forbidden = {item['archive']['path'] for item in q['targets']}
    builtin_open, io_open, os_open = builtins.open, io.open, os.open

    def check_path(path):
        if not isinstance(path, int):
            assert os.fspath(path) not in forbidden, 'check-only opened an archive'

    def safe_open(path, *args, **kwargs):
        check_path(path)
        return builtin_open(path, *args, **kwargs)

    def safe_io_open(path, *args, **kwargs):
        check_path(path)
        return io_open(path, *args, **kwargs)

    def safe_os_open(path, *args, **kwargs):
        check_path(path)
        return os_open(path, *args, **kwargs)

    monkeypatch.setattr(builtins, 'open', safe_open)
    monkeypatch.setattr(io, 'open', safe_io_open)
    monkeypatch.setattr(os, 'open', safe_os_open)
    qualification.validate(q)
    assert not Path(q['output_root']).exists()


